// RGB2HSV for libslic3r's FlushVolCalculator (purge volumes between
// filaments of different colours). Upstream it lives in the GUI library
// (src/slic3r/Utils/ColorSpaceConvert.cpp, which also pulls in wxWidgets);
// this is the same function, so the GUI-less builds link.

#include <algorithm>
#include <cmath>

void RGB2HSV(float r, float g, float b, float* h, float* s, float* v)
{
    float Cmax = std::max(std::max(r, g), b);
    float Cmin = std::min(std::min(r, g), b);
    float delta = Cmax - Cmin;

    if (std::abs(delta) < 0.001) {
        *h = 0.f;
    }
    else if (Cmax == r) {
        *h = 60.f * fmod((g - b) / delta, 6.f);
    }
    else if (Cmax == g) {
        *h = 60.f * ((b - r) / delta + 2);
    }
    else {
        *h = 60.f * ((r - g) / delta + 4);
    }

    if (std::abs(Cmax) < 0.001) {
        *s = 0.f;
    }
    else {
        *s = delta / Cmax;
    }

    *v = Cmax;
}
