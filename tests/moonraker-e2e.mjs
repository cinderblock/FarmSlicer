#!/usr/bin/env node
// End-to-end test of the Moonraker (Klipper) driver against the fake in
// tests/fake-moonraker/: connecting (with and without an API key), live
// status, sending plain G-code and following it to the end, pause / resume /
// stop / speed, pre-heating by material, pictures of prints started
// elsewhere, and Klipper shutting down.
//
//   node tests/moonraker-e2e.mjs http://localhost:9337
//
// Needs a fresh server (it performs first-run setup). Exit code 0 iff all
// checks pass. No dependencies beyond Node 22.
import { BASE, check, Client, SoftAuthenticator, register, finish } from "./lib.mjs";
import { startFakeMoonraker } from "./fake-moonraker/fake-moonraker.mjs";

console.log(`moonraker e2e against ${BASE}`);

const json = (r) => JSON.stringify(r.json);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const fake = await startFakeMoonraker({ apiKey: "secret-key", printSeconds: 3 });

const owner = new Client();
let r = await register(owner, new SoftAuthenticator(), "/api/auth/setup/start", { username: "owner" }, "/api/auth/setup/finish", "k");
check(r.status === 200, "owner set up", json(r));

async function statusOf(id, until, tries = 60) {
  let s;
  for (let i = 0; i < tries; i++) {
    r = await owner.get("/api/printers/status");
    s = r.json?.find((x) => x.printer_id === id);
    if (until(s)) return s;
    await sleep(250);
  }
  return s;
}

async function printOf(id, until, tries = 80) {
  let p;
  for (let i = 0; i < tries; i++) {
    r = await owner.get(`/api/prints/${id}`);
    p = r.json;
    if (until(p)) return p;
    await sleep(250);
  }
  return p;
}

// ---- connecting -------------------------------------------------------------------------
r = await owner.get("/api/printer-protocols");
const moonraker = r.json?.find((p) => p.id === "moonraker");
check(moonraker?.capabilities?.speed === "percent" && moonraker.capabilities.package === "gcode", "Moonraker is a protocol, taking G-code", json(r));

r = await owner.post("/api/printers", {
  name: "Bench Voron",
  machine_profile: "Voron 2.4 350",
  nozzle_diameter: "0.4",
  protocol: "moonraker",
  address: fake.address,
});
check(r.status === 201 && r.json.capabilities?.pause === true, "admin adds a Klipper printer", json(r));
const id = r.json.id;

let s = await statusOf(id, (x) => /API key|401/.test(x?.connection_error ?? ""));
check(s?.online === false && /API key/.test(s?.connection_error ?? ""), "without the API key the printer says what's missing", JSON.stringify(s));

r = await owner.patch(`/api/printers/${id}`, { access_code: "secret-key" });
check(r.status === 200 && r.json.access_code_set, "admin sets the API key", json(r));
s = await statusOf(id, (x) => x?.online && x.state === "IDLE");
check(s?.online && s.state === "IDLE" && s.vendor_state === "standby", "with it the printer connects and is idle", JSON.stringify(s));
check(s?.nozzles?.length === 1 && s.bed && s.speed_percent === 100, "temperatures and speed come through", JSON.stringify(s));

r = await owner.get(`/api/printers/${id}/report`);
check(r.status === 200 && r.json?.objects?.print_stats, "the raw view shows Klipper's objects", json(r));

// ---- sending plain G-code -----------------------------------------------------------------
const png = Buffer.from("89504e470d0a1a0a7468756d62", "hex");
const gcode = [
  "; HEADER_BLOCK_START",
  "; generated by OrcaSlicer 2.4.2 on 2026-10-13 at 10:00:00",
  "; HEADER_BLOCK_END",
  "",
  `; thumbnail begin 2x2 ${png.toString("base64").length}`,
  `; ${png.toString("base64")}`,
  "; thumbnail end",
  "",
  "G28",
  "G1 X10 Y10 E1",
  "; filament used [g] = 2.00",
  "; total filament used [g] = 2.00",
  "; total layers count = 10",
  "; estimated printing time (normal mode) = 3s",
  "; filament_type = PLA",
  "; filament_colour = #FF0000",
  "; nozzle_diameter = 0.4",
  "; printer_model = Voron 2.4 350",
  "",
].join("\n");
r = await owner.form("/api/uploads", { file: [new Blob([gcode]), "Clip.gcode"] });
check(r.status === 201, "plain G-code uploads", json(r));
const jobId = r.json.id;

r = await owner.get(`/api/jobs/${jobId}/targets`);
const target = r.json?.targets?.find((t) => t.printer_id === id);
check(target && target.incompatible === null && target.busy === null && target.problems.length === 0, "the Voron takes it and is free", json(r));

r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
check(r.status === 201 && r.json.file_name.endsWith(".gcode"), "send starts", json(r));
const first = r.json.id;
let p = await printOf(first, (x) => x?.status === "printing");
check(p?.status === "printing", "the print goes uploading → printing", JSON.stringify(p));
check(fake.files.has(`farmslicer/${p.file_name}`), "the file landed in gcodes/farmslicer/", JSON.stringify([...fake.files.keys()]));
s = await statusOf(id, (x) => x?.state === "RUNNING");
check(s?.job_key === p.file_name.replace(/\.gcode$/, "") && s.total_layers === 10, "status names the job and its layers", JSON.stringify(s));

r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
check(r.status === 409 && /printing|busy/.test(r.json.error), "a busy printer refuses another send", json(r));

p = await printOf(first, (x) => x?.status === "finished");
check(p?.status === "finished" && p.progress === 100, "the print finishes", JSON.stringify(p));

r = await fetch(`${BASE}/api/printers/${id}/thumbnail`, { headers: { cookie: owner.cookie } });
check(r.status === 200 && r.headers.get("content-type") === "image/png", "the printer card shows the job's picture", String(r.status));

// ---- controls -----------------------------------------------------------------------------
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
const second = r.json.id;
p = await printOf(second, (x) => x?.status === "printing");
check(p?.status === "printing", "a second print starts", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/control`, { action: "pause" });
check(r.status === 200, "pause", json(r));
p = await printOf(second, (x) => x?.status === "paused");
check(p?.status === "paused", "the print is paused", JSON.stringify(p));
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
check(r.status === 409, "a paused printer refuses another send (Klipper would replace the job)", json(r));
r = await owner.post(`/api/prints/${second}/control`, { action: "pause" });
check(r.status === 502 && /paused/.test(r.json.error), "pausing twice is refused", json(r));
r = await owner.post(`/api/prints/${second}/control`, { action: "resume" });
check(r.status === 200, "resume", json(r));
p = await printOf(second, (x) => x?.status === "printing");
check(p?.status === "printing", "printing again", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/control`, { action: "speed", percent: 50 });
check(r.status === 200, "speed 50%", json(r));
s = await statusOf(id, (x) => x?.speed_percent === 50);
check(s?.speed_percent === 50, "the speed factor shows", JSON.stringify(s));
r = await owner.post(`/api/prints/${second}/control`, { action: "stop" });
check(r.status === 200, "stop", json(r));
p = await printOf(second, (x) => x?.status === "cancelled");
check(p?.status === "cancelled", "a stopped print is cancelled", JSON.stringify(p));

// ---- heat -------------------------------------------------------------------------------
r = await owner.post(`/api/printers/${id}/preheat`, { material: "PETG" });
check(r.status === 200 && r.json.nozzle === 250 && r.json.bed === 70, "pre-heat for PETG", json(r));
s = await statusOf(id, (x) => x?.nozzles?.[0]?.target === 250 && x.bed?.target === 70);
check(s?.nozzles?.[0]?.target === 250 && s.bed?.target === 70, "the heaters have their targets", JSON.stringify(s));
check(fake.scripts.some((x) => /SET_HEATER_TEMPERATURE HEATER=extruder TARGET=250/.test(x)), "sent as SET_HEATER_TEMPERATURE", JSON.stringify(fake.scripts));
r = await owner.post(`/api/printers/${id}/cooldown`, {});
check(r.status === 200, "cool down", json(r));
s = await statusOf(id, (x) => x?.nozzles?.[0]?.target === 0 && x.bed?.target === 0);
check(s?.nozzles?.[0]?.target === 0, "the heaters are off", JSON.stringify(s));

// ---- prints started elsewhere, Klipper shutting down ------------------------------------
await fetch(`http://${fake.address}/__fake/outside-print`, { method: "POST" });
s = await statusOf(id, (x) => x?.job_key === "Outside_Print");
check(s?.job_key === "Outside_Print" && ["PREPARE", "RUNNING"].includes(s.state), "a print from elsewhere shows", JSON.stringify(s));
r = await fetch(`${BASE}/api/printers/${id}/thumbnail`, { headers: { cookie: owner.cookie } });
const picture = Buffer.from(await r.arrayBuffer());
check(r.status === 200 && picture.toString("hex").includes("6f7574736964652d7072696e74"), "its picture comes from the printer's thumbnails", String(r.status));

await fetch(`http://${fake.address}/__fake/shutdown`, { method: "POST" });
s = await statusOf(id, (x) => x?.state === "FAILED");
check(s?.state === "FAILED" && /Emergency stop/.test(s.message ?? ""), "Klipper shutting down shows as an error", JSON.stringify(s));

r = await owner.del(`/api/printers/${id}`);
check(r.status === 204, "admin removes the printer", json(r));

await fake.close();
finish();
