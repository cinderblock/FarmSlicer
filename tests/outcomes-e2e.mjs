#!/usr/bin/env node
// End-to-end test of print outcomes (src/outcomes.rs) against the fake
// Klipper printer: a finished plate waits to be checked, its copies are
// counted per kind of part (from the project's object list), bad counts
// and reasons are refused, a stopped print is recorded as failed by the
// printer, people can correct a record, and the site can count finished
// prints good on its own.
//
//   node tests/outcomes-e2e.mjs http://localhost:9337
//
// Needs a fresh server (it performs first-run setup). Exit code 0 iff all
// checks pass.
import { BASE, check, Client, SoftAuthenticator, register, finish, zip } from "./lib.mjs";
import { startFakeMoonraker } from "./fake-moonraker/fake-moonraker.mjs";

console.log(`outcomes e2e against ${BASE}`);

const json = (r) => JSON.stringify(r.json);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const fake = await startFakeMoonraker({ printSeconds: 2 });

const owner = new Client();
let r = await register(owner, new SoftAuthenticator(), "/api/auth/setup/start", { username: "owner" }, "/api/auth/setup/finish", "k");
check(r.status === 200, "owner set up", json(r));

r = await owner.post("/api/printers", {
  name: "Voron A",
  machine_profile: "Voron 2.4 350",
  nozzle_diameter: "0.4",
  protocol: "moonraker",
  address: fake.address,
});
check(r.status === 201, "a Klipper printer", json(r));
const printer = r.json.id;

async function until(path, ok, tries = 80) {
  let v;
  for (let i = 0; i < tries; i++) {
    r = await owner.get(path);
    v = r.json;
    if (ok(v)) return v;
    await sleep(250);
  }
  return v;
}
await until("/api/printers/status", (l) => l?.find((s) => s.printer_id === printer)?.state === "IDLE");

// A project of two plates: plate 1 holds three brackets and a clip.
const gcode = (n) =>
  [
    "; generated by OrcaSlicer 2.4.2",
    `G1 X${n}0 Y10 E1`,
    "; total filament used [g] = 2.00",
    "; estimated printing time (normal mode) = 2s",
    "; filament_type = PLA",
    "; nozzle_diameter = 0.4",
    "; printer_model = Voron 2.4 350",
  ].join("\n");
const sliceInfo = `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <plate>
    <metadata key="index" value="1"/>
    <object identify_id="1" name="Bracket" skipped="false"/>
    <object identify_id="2" name="Bracket" skipped="false"/>
    <object identify_id="3" name="Clip" skipped="false"/>
    <object identify_id="4" name="Bracket" skipped="false"/>
    <object identify_id="5" name="Spare" skipped="true"/>
  </plate>
  <plate>
    <metadata key="index" value="2"/>
    <object identify_id="6" name="Clip" skipped="false"/>
  </plate>
</config>`;
const project = zip({
  "Metadata/plate_1.gcode": gcode(1),
  "Metadata/plate_2.gcode": gcode(2),
  "Metadata/slice_info.config": sliceInfo,
  "Metadata/project_settings.config": JSON.stringify({ printer_model: "Voron 2.4 350" }),
});
r = await owner.form("/api/uploads", { file: [new Blob([project]), "Brackets.gcode.3mf"] });
check(r.status === 201, "the project uploads", json(r));
const job = r.json.id;
const pkg = JSON.parse(r.json.package_json ?? "{}");
check(pkg.plates?.[0]?.objects?.length === 4, "the package lists plate 1's objects (the skipped one left out)", r.json.package_json);

r = await owner.get("/api/outcome-reasons");
check(r.status === 200 && r.json.some((x) => x.id === "spaghetti") && r.json.every((x) => x.label), "the reasons have labels", json(r));

// ---- a finished print waits to be checked ------------------------------------------------
r = await owner.post(`/api/jobs/${job}/print`, { printer_id: printer, plate: 1, acknowledge_review: true });
check(r.status === 201, "plate 1 goes to the printer", json(r));
const first = r.json.id;
r = await owner.post(`/api/prints/${first}/outcome`, { all: "good" });
check(r.status === 409 && /ended/.test(r.json.error), "no outcome while it prints", json(r));
let p = await until(`/api/prints/${first}`, (x) => x?.status === "finished");
check(p.status === "finished" && p.outcome === null && p.can_record_outcome, "it finishes, unchecked", JSON.stringify(p));
const lines = p.lines ?? [];
check(
  lines.length === 2 && lines[0].name === "Bracket" && lines[0].planned === 3 && lines[1].name === "Clip" && lines[1].planned === 1 && lines[0].good === null,
  "its lines: 3 brackets, 1 clip",
  JSON.stringify(lines),
);
r = await owner.get("/api/prints?unchecked=1");
check(r.json.map((x) => x.id).includes(first), "it is on the unchecked list", json(r));

// ---- recording it ------------------------------------------------------------------------
r = await owner.post(`/api/prints/${first}/outcome`, { lines: [{ line: 0, good: 2, failed: 0 }], all: "good" });
check(r.status === 400 && /3 cop/.test(r.json.error), "counts must add up to the copies", json(r));
r = await owner.post(`/api/prints/${first}/outcome`, { lines: [{ line: 0, good: 2, failed: 1 }], all: "good" });
check(r.status === 400 && /why/.test(r.json.error), "failed copies need a reason", json(r));
r = await owner.post(`/api/prints/${first}/outcome`, { lines: [{ line: 0, good: 2, failed: 1, reason: "gremlins" }], all: "good" });
check(r.status === 400 && /gremlins/.test(r.json.error), "an unknown reason is refused", json(r));
r = await owner.post(`/api/prints/${first}/outcome`, { lines: [{ line: 0, good: 2, failed: 1, reason: "spaghetti" }] });
check(r.status === 400 && /Clip/.test(r.json.error), "every line must be accounted for", json(r));
r = await owner.post(`/api/prints/${first}/outcome`, {
  lines: [{ line: 0, good: 2, failed: 1, reason: "spaghetti" }],
  all: "good",
  note: "one came loose at layer 40",
});
check(r.status === 200 && r.json.outcome === "partial" && r.json.outcome_by === "owner", "2 of 3 brackets and the clip: partial", json(r));
check(
  r.json.lines[0].good === 2 && r.json.lines[0].failed === 1 && r.json.lines[0].reason === "spaghetti" && r.json.lines[1].good === 1,
  "the lines carry the counts",
  JSON.stringify(r.json.lines),
);
check(r.json.outcome_note === "one came loose at layer 40", "and the note", json(r));
r = await owner.get("/api/prints?unchecked=1");
check(!r.json.map((x) => x.id).includes(first), "checked prints leave the unchecked list", json(r));

// ---- a stopped print is recorded failed --------------------------------------------------
r = await owner.post(`/api/jobs/${job}/print`, { printer_id: printer, plate: 1, acknowledge_review: true });
const second = r.json.id;
await until(`/api/prints/${second}`, (x) => x?.status === "printing" && x.started_at);
r = await owner.post(`/api/prints/${second}/control`, { action: "stop" });
check(r.status === 200, "stop it", json(r));
p = await until(`/api/prints/${second}`, (x) => x?.status === "cancelled" && x.outcome);
check(p.outcome === "failed" && p.outcome_by === "printer" && p.lines.every((l) => l.failed === l.planned && l.reason === "cancelled"), "the printer's record: every copy failed, cancelled", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/outcome`, {
  lines: [{ line: 0, good: 3, failed: 0 }, { line: 1, good: 0, failed: 1, reason: "adhesion" }],
});
check(r.status === 200 && r.json.outcome === "partial" && r.json.outcome_by === "owner", "a person corrects it", json(r));

// ---- the site counts finished prints good ------------------------------------------------
r = await owner.put("/api/settings", { finished_outcome: "sometimes" });
check(r.status === 400, "finished_outcome: ask or good", json(r));
r = await owner.put("/api/settings", { finished_outcome: "good" });
check(r.status === 200 && r.json.finished_outcome === "good", "finished prints count as good", json(r));
await until("/api/printers/status", (l) => ["IDLE", "CANCELLED", "FINISH"].includes(l?.find((s) => s.printer_id === printer)?.state));
r = await owner.post(`/api/jobs/${job}/print`, { printer_id: printer, plate: 2, acknowledge_review: true });
check(r.status === 201, "plate 2 goes out", json(r));
p = await until(`/api/prints/${r.json.id}`, (x) => x?.status === "finished" && x.outcome);
check(p.outcome === "good" && p.outcome_by === "auto" && p.lines.length === 1 && p.lines[0].name === "Clip" && p.lines[0].good === 1, "it is recorded good on its own", JSON.stringify(p));

await fake.close();
finish();
