#!/usr/bin/env node
// End-to-end test of the PrusaLink driver against the fake in
// tests/fake-prusalink/: connecting with the PrusaLink password, polled
// status, sending plain G-code (folder, upload, start) and following it to
// FINISHED, pause / resume / stop, what PrusaLink can't do (speed, heat,
// camera), the screen asking a question (ATTENTION), and pictures of
// prints started at the printer.
//
//   node tests/prusalink-e2e.mjs http://localhost:9337
//
// Needs a fresh server (it performs first-run setup). Exit code 0 iff all
// checks pass. No dependencies beyond Node 22.
import { BASE, check, Client, SoftAuthenticator, register, finish } from "./lib.mjs";
import { startFakePrusaLink } from "./fake-prusalink/fake-prusalink.mjs";

console.log(`prusalink e2e against ${BASE}`);

const json = (r) => JSON.stringify(r.json);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const fake = await startFakePrusaLink({ password: "pl-secret", printSeconds: 8 });
const hook = (name) => fetch(`http://${fake.address}/__fake/${name}`, { method: "POST" });

const owner = new Client();
let r = await register(owner, new SoftAuthenticator(), "/api/auth/setup/start", { username: "owner" }, "/api/auth/setup/finish", "k");
check(r.status === 200, "owner set up", json(r));

async function statusOf(id, until, tries = 60) {
  let s;
  for (let i = 0; i < tries; i++) {
    r = await owner.get("/api/printers/status");
    s = r.json?.find((x) => x.printer_id === id);
    if (until(s)) return s;
    await sleep(250);
  }
  return s;
}

async function printOf(id, until, tries = 80) {
  let p;
  for (let i = 0; i < tries; i++) {
    r = await owner.get(`/api/prints/${id}`);
    p = r.json;
    if (until(p)) return p;
    await sleep(250);
  }
  return p;
}

// ---- connecting -------------------------------------------------------------------------
r = await owner.get("/api/printer-protocols");
const prusa = r.json?.find((p) => p.id === "prusalink");
check(prusa?.capabilities?.pause && !prusa.capabilities.heat && prusa.capabilities.speed === null && !prusa.capabilities.camera, "PrusaLink: pause and stop, no heat, speed or camera", json(r));

r = await owner.post("/api/printers", {
  name: "Bench MK4S",
  machine_profile: "Prusa MK4S",
  nozzle_diameter: "0.4",
  protocol: "prusalink",
  address: fake.address,
  access_code: "wrong",
});
const id = r.json.id;
let s = await statusOf(id, (x) => /password/.test(x?.connection_error ?? ""));
check(s?.online === false && /PrusaLink refused the password/.test(s?.connection_error ?? ""), "a wrong password says so", JSON.stringify(s));
r = await owner.patch(`/api/printers/${id}`, { access_code: "pl-secret" });
s = await statusOf(id, (x) => x?.online && x.state === "IDLE");
check(s?.online && s.state === "IDLE" && s.vendor_state === "IDLE", "with the password it's polled and idle", JSON.stringify(s));
check(s?.nozzles?.[0]?.current === 24 && s.bed?.current === 23, "temperatures come through", JSON.stringify(s));

// ---- sending ------------------------------------------------------------------------------
const png = Buffer.from("89504e470d0a1a0a707275736130", "hex");
const gcode = (model) =>
  [
    "; generated by OrcaSlicer 2.4.2 on 2026-10-13 at 10:00:00",
    "; thumbnail_QOI begin 16x16 8",
    "; cW9pZg==",
    "; thumbnail_QOI end",
    `; thumbnail begin 64x48 ${png.toString("base64").length}`,
    `; ${png.toString("base64")}`,
    "; thumbnail end",
    "M862.3 P \"MK4S\"",
    "G28",
    "G1 X10 Y10 E1",
    "; total filament used [g] = 1.00",
    "; estimated printing time (normal mode) = 4s",
    "; filament_type = PLA",
    "; nozzle_diameter = 0.4",
    `; printer_model = ${model}`,
    "",
  ].join("\n");
r = await owner.form("/api/uploads", { file: [new Blob([gcode("Prusa MK4S")]), "Spool Clip (v2).gcode"] });
const jobId = r.json.id;
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
check(r.status === 201 && /^[A-Za-z0-9._-]+$/.test(r.json.file_name), "send starts, with a plain ASCII file name", json(r));
const first = r.json.id;
let p = await printOf(first, (x) => x?.status === "printing");
check(p?.status === "printing", "the print goes uploading → printing", JSON.stringify(p));
check(fake.files.has(`usb/farmslicer/${p.file_name}`), "the file landed in usb/farmslicer/", JSON.stringify([...fake.files.keys()]));
s = await statusOf(id, (x) => x?.state === "RUNNING" && x.job_key);
check(s?.job_key === p.file_name.replace(/\.gcode$/, "") && s.percent !== null, "status names the job (by its long name)", JSON.stringify(s));
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
check(r.status === 409, "a busy printer refuses another send", json(r));
p = await printOf(first, (x) => x?.status === "finished");
check(p?.status === "finished", "FINISHED (with the job gone from the status) finishes the print", JSON.stringify(p));
s = await statusOf(id, (x) => x?.state === "FINISH");
check(s?.job_key === p.file_name.replace(/\.gcode$/, ""), "the finished job is still named", JSON.stringify(s));

// ---- controls -----------------------------------------------------------------------------
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
const second = r.json.id;
p = await printOf(second, (x) => x?.status === "printing");
check(p?.status === "printing", "a print starts from the finish screen", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/control`, { action: "pause" });
check(r.status === 200, "pause", json(r));
p = await printOf(second, (x) => x?.status === "paused");
check(p?.status === "paused", "paused", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/control`, { action: "resume" });
p = await printOf(second, (x) => x?.status === "printing");
check(p?.status === "printing", "resumed", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/control`, { action: "speed", percent: 120 });
check(r.status === 409 && /speed/.test(r.json.error), "speed isn't offered over PrusaLink", json(r));
r = await owner.post(`/api/prints/${second}/control`, { action: "stop" });
check(r.status === 200, "stop", json(r));
p = await printOf(second, (x) => x?.status === "cancelled");
check(p?.status === "cancelled", "STOPPED cancels the print", JSON.stringify(p));
r = await owner.post(`/api/printers/${id}/preheat`, { material: "PLA" });
check(r.status === 409 && /temperatures/.test(r.json.error), "pre-heating isn't offered over PrusaLink", json(r));

// ---- the printer asks a question; prints from the screen ----------------------------------
await hook("clear");
await hook("attention");
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
const third = r.json.id;
const thirdKey = r.json.file_name.replace(/\.gcode$/, "");
s = await statusOf(id, (x) => x?.vendor_state === "ATTENTION");
check(s?.state === "PAUSE" && /someone at the printer/.test(s.message ?? "") && s.job_key === thirdKey, "a question on the screen: waiting at the printer, our job named", JSON.stringify(s));
await hook("answer");
p = await printOf(third, (x) => x?.status === "printing");
check(p?.status === "printing", "answered at the printer: printing", JSON.stringify(p));
r = await owner.post(`/api/prints/${third}/control`, { action: "stop" });
p = await printOf(third, (x) => x?.status === "cancelled");
check(p?.status === "cancelled", "stopped", JSON.stringify(p));

await hook("clear");
fake.outsidePrint("usb/Outside.gcode", Buffer.from(gcode("Prusa MK4S")));
s = await statusOf(id, (x) => x?.job_key === "Outside");
check(s?.state === "RUNNING", "a print started at the printer shows", JSON.stringify(s));
r = await fetch(`${BASE}/api/printers/${id}/thumbnail`, { headers: { cookie: owner.cookie } });
const pic = Buffer.from(await r.arrayBuffer());
check(r.status === 200 && pic.equals(png), "its picture is PrusaLink's preview (the PNG, not the QOI)", String(r.status));

await hook("busy");
s = await statusOf(id, (x) => x?.vendor_state === "BUSY");
check(s?.state === null && /busy/.test(s.message ?? ""), "BUSY is neither idle nor printing", JSON.stringify(s));

r = await owner.del(`/api/printers/${id}`);
check(r.status === 204, "admin removes the printer", json(r));
await fake.close();
finish();
