#!/usr/bin/env node
// End-to-end test of the Elegoo SDCP driver against the fake in
// tests/fake-sdcp/: connecting (no password; the mainboard id is learnt),
// status asked for while the printer is quiet, sending plain G-code (1 MiB
// parts, the file check, Cmd 128 with Elegoo's exact payload) and following
// it to the end, pause / resume / stop, speed presets and temperatures,
// the camera, and the picture the printer keeps per task. Throughout: no
// command the printer wouldn't expect (the fake "crashes" on those).
//
//   node tests/sdcp-e2e.mjs http://localhost:9337
//
// Needs a fresh server (it performs first-run setup). Exit code 0 iff all
// checks pass. No dependencies beyond Node 22.
import { BASE, check, Client, SoftAuthenticator, register, finish } from "./lib.mjs";
import { startFakeSdcp } from "./fake-sdcp/fake-sdcp.mjs";

console.log(`sdcp e2e against ${BASE}`);

const json = (r) => JSON.stringify(r.json);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const fake = await startFakeSdcp({ printSeconds: 4 });

const owner = new Client();
let r = await register(owner, new SoftAuthenticator(), "/api/auth/setup/start", { username: "owner" }, "/api/auth/setup/finish", "k");
check(r.status === 200, "owner set up", json(r));

async function statusOf(id, until, tries = 60) {
  let s;
  for (let i = 0; i < tries; i++) {
    r = await owner.get("/api/printers/status");
    s = r.json?.find((x) => x.printer_id === id);
    if (until(s)) return s;
    await sleep(250);
  }
  return s;
}

async function printOf(id, until, tries = 80) {
  let p;
  for (let i = 0; i < tries; i++) {
    r = await owner.get(`/api/prints/${id}`);
    p = r.json;
    if (until(p)) return p;
    await sleep(250);
  }
  return p;
}

// ---- connecting -------------------------------------------------------------------------
r = await owner.post("/api/printers", {
  name: "Bench Carbon",
  machine_profile: "Elegoo Centauri Carbon",
  nozzle_diameter: "0.4",
  protocol: "sdcp",
  address: fake.address,
});
check(r.status === 201 && r.json.configured === true, "an address is all it needs", json(r));
const id = r.json.id;
let s = await statusOf(id, (x) => x?.online && x.state === "IDLE");
check(s?.online && s.state === "IDLE" && s.nozzles?.[0]?.current === 26 && s.chamber === 24, "connected, idle, temperatures and the chamber", JSON.stringify(s));
r = await owner.get(`/api/printers/${id}/report`);
check(r.json?.mainboard_id === fake.mainboard && r.json?.attributes?.MachineName === "Centauri Carbon", "the mainboard id and attributes are learnt", json(r));

// ---- sending: more than one 1 MiB part ----------------------------------------------------
const png = Buffer.from("89504e470d0a1a0a63617262", "hex");
const filler = Array.from({ length: 30000 }, (_, i) => `G1 X${(i % 200) + 10} Y${(i % 150) + 10} E0.01 F3000 ; padding to make the file span two upload parts`).join("\n");
const gcode = [
  "; HEADER_BLOCK_START",
  "; generated by OrcaSlicer 2.4.2 on 2026-10-13 at 10:00:00",
  "; HEADER_BLOCK_END",
  `; thumbnail begin 144x144 ${png.toString("base64").length}`,
  `; ${png.toString("base64")}`,
  "; thumbnail end",
  "G28",
  filler,
  "; total filament used [g] = 3.00",
  "; estimated printing time (normal mode) = 4s",
  "; filament_type = PLA",
  "; nozzle_diameter = 0.4",
  "; printer_model = Elegoo Centauri Carbon",
  "; curr_bed_type = Cool Plate",
  "",
].join("\n");
check(gcode.length > 1 << 20, "the test file is bigger than one upload part", String(gcode.length));
r = await owner.form("/api/uploads", { file: [new Blob([gcode]), "Carbon Clip.gcode"] });
const jobId = r.json.id;
r = await owner.get(`/api/jobs/${jobId}/targets`);
const t = r.json?.targets?.find((x) => x.printer_id === id);
check(t && t.incompatible === null && t.capabilities?.print_options?.join() === "bed_leveling,timelapse", "the Carbon takes it; levelling and timelapse are the options", json(r));
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id, acknowledge_review: true, options: { bed_leveling: false, timelapse: true } });
check(r.status === 201, "send starts", json(r));
const first = r.json.id;
let p = await printOf(first, (x) => x?.status === "printing");
check(p?.status === "printing", "the print goes uploading → printing", JSON.stringify(p));
check(fake.files.get(`/local/${p.file_name}`)?.length === Buffer.byteLength(gcode), "the file arrived whole (MD5 checked)", "");
const start = fake.received.find((c) => c.cmd === 128)?.data;
check(
  start?.Filename === `/local/${p.file_name}` && start.Calibration_switch === 0 && start.Tlp_Switch === 1 && start.PrintPlatformType === 1 && start.StartLayer === 0,
  "Cmd 128 with Elegoo's payload, the options and the smooth plate side",
  JSON.stringify(start),
);
s = await statusOf(id, (x) => x?.state === "RUNNING");
check(s?.job_key === p.file_name.replace(/\.gcode$/, "") && s.total_layers === 20, "status names the job and its layers", JSON.stringify(s));
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id, acknowledge_review: true });
check(r.status === 409, "a busy printer refuses another send", json(r));
p = await printOf(first, (x) => x?.status === "finished");
check(p?.status === "finished", "the print finishes (status 9)", JSON.stringify(p));
r = await fetch(`${BASE}/api/printers/${id}/thumbnail`, { headers: { cookie: owner.cookie } });
check(r.status === 200, "the printer card shows the job's picture", String(r.status));

// ---- controls -----------------------------------------------------------------------------
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id, acknowledge_review: true });
const second = r.json.id;
p = await printOf(second, (x) => x?.status === "printing");
check(p?.status === "printing", "a second print starts", JSON.stringify(p));
await statusOf(id, (x) => x?.state === "RUNNING");
r = await owner.post(`/api/prints/${second}/control`, { action: "pause" });
p = await printOf(second, (x) => x?.status === "paused");
check(p?.status === "paused", "pause (5 → 6)", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/control`, { action: "resume" });
p = await printOf(second, (x) => x?.status === "printing");
check(p?.status === "printing", "resume (12 → 13)", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/control`, { action: "speed", level: 4 });
s = await statusOf(id, (x) => x?.speed_level === 4);
check(s?.speed_percent === 160 && s.speed_level === 4, "ludicrous is 160 %", JSON.stringify(s));
r = await owner.post(`/api/prints/${second}/control`, { action: "stop" });
p = await printOf(second, (x) => x?.status === "cancelled");
check(p?.status === "cancelled", "stop (7 → 8) cancels", JSON.stringify(p));

r = await owner.post(`/api/printers/${id}/preheat`, { material: "PETG" });
check(r.status === 200 && fake.status.TempTargetNozzle === 250 && fake.status.TempTargetHotbed === 70, "pre-heat over Cmd 403", json(r));
r = await owner.post(`/api/printers/${id}/cooldown`, {});
check(r.status === 200 && fake.status.TempTargetNozzle === 0, "cool down", json(r));

// ---- camera ----------------------------------------------------------------------------
const frames = await new Promise((resolve) => {
  const ws = new WebSocket(`${BASE.replace("http", "ws")}/api/printers/${id}/camera`, { headers: { cookie: owner.cookie } });
  ws.binaryType = "arraybuffer";
  let n = 0;
  let hello = null;
  ws.onmessage = (e) => {
    if (typeof e.data === "string") hello = JSON.parse(e.data);
    else n++;
  };
  ws.onerror = () => resolve({ hello, n, error: true });
  setTimeout(() => {
    ws.close();
    resolve({ hello, n });
  }, 2500);
});
check(frames.hello?.kind === "jpeg" && frames.n >= 3, "the camera streams JPEG frames", JSON.stringify(frames));
check(fake.received.some((c) => c.cmd === 386 && c.data?.Enable === 1), "after switching it on (Cmd 386)", "");

check(fake.crashes.length === 0, "nothing the printer wouldn't expect was ever sent", JSON.stringify(fake.crashes));
const unexpected = fake.received.filter((c) => ![0, 1, 128, 129, 130, 131, 386, 403].includes(c.cmd));
check(unexpected.length === 0, "only Elegoo's own commands", JSON.stringify(unexpected));

r = await owner.del(`/api/printers/${id}`);
check(r.status === 204, "admin removes the printer", json(r));
await fake.close();
finish();
