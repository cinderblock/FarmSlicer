#!/usr/bin/env node
// End-to-end test of the OctoPrint driver against the fake in
// tests/fake-octoprint/: connecting (the API key is required), live status,
// sending plain G-code and following it to the end, pause / resume / stop /
// speed, pre-heating, pictures of prints started elsewhere, and the two
// kinds of offline (OctoPrint up without its printer; a printer error).
//
//   node tests/octoprint-e2e.mjs http://localhost:9337
//
// Needs a fresh server (it performs first-run setup). Exit code 0 iff all
// checks pass. No dependencies beyond Node 22.
import { BASE, check, Client, SoftAuthenticator, register, finish } from "./lib.mjs";
import { startFakeOctoPrint } from "./fake-octoprint/fake-octoprint.mjs";

console.log(`octoprint e2e against ${BASE}`);

const json = (r) => JSON.stringify(r.json);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const fake = await startFakeOctoPrint({ apiKey: "octo-key", printSeconds: 3 });
const hook = (name) => fetch(`http://${fake.address}/__fake/${name}`, { method: "POST" });

const owner = new Client();
let r = await register(owner, new SoftAuthenticator(), "/api/auth/setup/start", { username: "owner" }, "/api/auth/setup/finish", "k");
check(r.status === 200, "owner set up", json(r));

async function statusOf(id, until, tries = 60) {
  let s;
  for (let i = 0; i < tries; i++) {
    r = await owner.get("/api/printers/status");
    s = r.json?.find((x) => x.printer_id === id);
    if (until(s)) return s;
    await sleep(250);
  }
  return s;
}

async function printOf(id, until, tries = 80) {
  let p;
  for (let i = 0; i < tries; i++) {
    r = await owner.get(`/api/prints/${id}`);
    p = r.json;
    if (until(p)) return p;
    await sleep(250);
  }
  return p;
}

// ---- connecting -------------------------------------------------------------------------
r = await owner.get("/api/printer-protocols");
const octo = r.json?.find((p) => p.id === "octoprint");
check(octo?.connection?.fields?.find((f) => f.key === "access_code")?.required === true, "OctoPrint needs an API key", json(r));

r = await owner.post("/api/printers", {
  name: "Bench Prusa",
  machine_profile: "Prusa MK3S",
  nozzle_diameter: "0.4",
  protocol: "octoprint",
  address: fake.address,
});
check(r.status === 201 && r.json.configured === false, "without the key the printer isn't connected", json(r));
const id = r.json.id;

r = await owner.patch(`/api/printers/${id}`, { access_code: "wrong" });
let s = await statusOf(id, (x) => /API key/.test(x?.connection_error ?? ""));
check(s?.online === false && /API key/.test(s?.connection_error ?? ""), "a wrong key says so", JSON.stringify(s));

r = await owner.patch(`/api/printers/${id}`, { access_code: "octo-key" });
s = await statusOf(id, (x) => x?.online && x.state === "IDLE");
check(s?.online && s.state === "IDLE" && s.vendor_state === "Operational", "with the key it connects and is idle", JSON.stringify(s));
check(s?.nozzles?.length === 1 && s.bed, "temperatures come through", JSON.stringify(s));

// ---- sending ------------------------------------------------------------------------------
const png = Buffer.from("89504e470d0a1a0a6f6374", "hex");
const gcode = [
  "; generated by OrcaSlicer 2.4.2 on 2026-10-13 at 10:00:00",
  `; thumbnail begin 2x2 ${png.toString("base64").length}`,
  `; ${png.toString("base64")}`,
  "; thumbnail end",
  "G28",
  "G1 X10 Y10 E1",
  "; total filament used [g] = 1.00",
  "; estimated printing time (normal mode) = 3s",
  "; filament_type = PETG",
  "; nozzle_diameter = 0.4",
  "",
].join("\n");
r = await owner.form("/api/uploads", { file: [new Blob([gcode]), "Hook.gcode"] });
const jobId = r.json.id;
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
check(r.status === 201, "send starts", json(r));
const first = r.json.id;
let p = await printOf(first, (x) => x?.status === "printing");
check(p?.status === "printing", "the print goes uploading → printing", JSON.stringify(p));
check(fake.files.has(`farmslicer/${p.file_name}`), "the file landed in farmslicer/", JSON.stringify([...fake.files.keys()]));
check(fake.files.get(`farmslicer/${p.file_name}`)?.userdata?.farmslicer?.print_id === first, "tagged with the print", "");
s = await statusOf(id, (x) => x?.state === "RUNNING");
check(s?.job_key === p.file_name.replace(/\.gcode$/, "") && s.remaining_minutes !== null, "status names the job", JSON.stringify(s));
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
check(r.status === 409, "a busy printer refuses another send", json(r));
p = await printOf(first, (x) => x?.status === "finished");
check(p?.status === "finished", "the print finishes (PrintDone)", JSON.stringify(p));
s = await statusOf(id, (x) => x?.state === "FINISH");
check(s?.state === "FINISH", "OctoPrint's 'Operational' with the file still selected reads as finished", JSON.stringify(s));

// ---- controls -----------------------------------------------------------------------------
r = await owner.post(`/api/jobs/${jobId}/print`, { printer_id: id });
const second = r.json.id;
p = await printOf(second, (x) => x?.status === "printing");
check(p?.status === "printing", "a second print starts on the finished printer", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/control`, { action: "pause" });
check(r.status === 200, "pause", json(r));
p = await printOf(second, (x) => x?.status === "paused");
check(p?.status === "paused", "paused", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/control`, { action: "resume" });
p = await printOf(second, (x) => x?.status === "printing");
check(p?.status === "printing", "resumed", JSON.stringify(p));
r = await owner.post(`/api/prints/${second}/control`, { action: "speed", percent: 150 });
check(r.status === 200 && Number.isInteger(fake.feedrates.at(-1)) && fake.feedrates.at(-1) === 150, "speed goes as an integer percent", JSON.stringify(fake.feedrates));
s = await statusOf(id, (x) => x?.speed_percent === 150);
check(s?.speed_percent === 150, "the speed we set shows", JSON.stringify(s));
r = await owner.post(`/api/prints/${second}/control`, { action: "stop" });
check(r.status === 200, "stop", json(r));
p = await printOf(second, (x) => x?.status === "cancelled");
check(p?.status === "cancelled", "a cancel (PrintCancelled + PrintFailed{cancelled}) is cancelled, not failed", JSON.stringify(p));

// ---- heat, pictures -----------------------------------------------------------------------
r = await owner.post(`/api/printers/${id}/preheat`, { material: "PLA" });
check(r.status === 200 && fake.temps.tool0.target === 220 && fake.temps.bed.target === 60, "pre-heat for PLA", json(r));
r = await owner.post(`/api/printers/${id}/cooldown`, {});
check(r.status === 200 && fake.temps.tool0.target === 0, "cool down", json(r));

await hook("outside-print");
s = await statusOf(id, (x) => x?.job_key === "Outside_Print");
check(s?.state === "RUNNING", "a print from elsewhere shows", JSON.stringify(s));
r = await fetch(`${BASE}/api/printers/${id}/thumbnail`, { headers: { cookie: owner.cookie } });
const pic = Buffer.from(await r.arrayBuffer());
check(r.status === 200 && pic.toString("hex").includes("6f63746f2d6f757473696465"), "its picture comes from the Slicer Thumbnails plugin", String(r.status));

// ---- the two offlines -----------------------------------------------------------------
await hook("disconnect");
s = await statusOf(id, (x) => x && !x.online);
check(!s?.online && /not connected to the printer/.test(s?.connection_error ?? ""), "OctoPrint without its printer is offline, saying why", JSON.stringify(s));
await hook("reconnect");
s = await statusOf(id, (x) => x?.online);
check(s?.online, "back when the printer is", JSON.stringify(s));
await hook("fail");
s = await statusOf(id, (x) => /Heater/.test(x?.message ?? ""));
check(s?.state === "FAILED" && /Heater failure/.test(s.message ?? ""), "a printer error shows its text", JSON.stringify(s));

r = await owner.del(`/api/printers/${id}`);
check(r.status === 204, "admin removes the printer", json(r));
await fake.close();
finish();
