// Unit tests of the G-code preview's parser (src/components/preview/parser.ts)
// on small synthetic files: `bun test` in web/.
import { describe, expect, test } from "bun:test";
import { GcodeParser, parseDuration, parseGcode } from "../src/components/preview/parser";
import { GAP, RETRACT, UNRETRACT, WIPE, type ParsedGcode } from "../src/components/preview/types";

/** The extruding segments (gaps left out) as [x0, y0, z0, x1, y1, z1]. */
function segments(p: ParsedGcode): number[][] {
  const out: number[][] = [];
  const { points, feature, count } = p.extrusions;
  for (let i = 0; i < count; i++) {
    if (feature[i] === GAP) continue;
    out.push([...points.subarray(i * 3, i * 3 + 6)].map((v) => Math.round(v * 1000) / 1000));
  }
  return out;
}

const featureOf = (p: ParsedGcode, i: number) => p.info.features[p.extrusions.feature[i]];
const width = (p: ParsedGcode, i: number) => p.extrusions.size[i * 2] / 1000;
const height = (p: ParsedGcode, i: number) => p.extrusions.size[i * 2 + 1] / 1000;

describe("layers", () => {
  test("from OrcaSlicer's generic comments", () => {
    const p = parseGcode(`; generated by OrcaSlicer 2.4.2 on 2026-10-16 at 10:46:00
G90
M83
;TYPE:Custom
G1 X0 Y0 Z0.3 F6000
G1 X50 E2 F1200
;LAYER_CHANGE
;Z:0.2
;HEIGHT:0.2
G1 Z0.2
;TYPE:Outer wall
;WIDTH:0.42
G1 X10 Y10 F9000
G1 X20 Y10 E0.5 F3000
G1 X20 Y20 E0.5
;TYPE:Sparse infill
;WIDTH:0.45
G1 X10 Y20 E0.5
;LAYER_CHANGE
;Z:0.4
;HEIGHT:0.2
G1 Z0.4
;TYPE:Outer wall
;WIDTH:0.42
G1 X20 Y10 E0.5
`);
    expect(p.info.generator).toBe("OrcaSlicer 2.4.2");
    expect(p.info.layerComments).toBe(true);
    expect(p.layers.count).toBe(2);
    expect([...p.layers.z].map((z) => +z.toFixed(3))).toEqual([0.2, 0.4]);
    expect([...p.layers.height].map((h) => +h.toFixed(3))).toEqual([0.2, 0.2]);
    // The start sequence's purge line shows with the first layer.
    expect(p.layers.extrusionStart[0]).toBe(0);
    const segs = segments(p);
    expect(segs[0]).toEqual([0, 0, 0.3, 50, 0, 0.3]);
    expect(featureOf(p, 0)).toBe("Custom");
    // Layer 2 starts with the gap from (10,20) to (10,20,0.4)... then its wall.
    const l2 = p.layers.extrusionStart[1];
    const firstWall = [...p.extrusions.feature.subarray(l2)].findIndex((f) => f !== GAP) + l2;
    expect(featureOf(p, firstWall)).toBe("Outer wall");
    expect(width(p, firstWall)).toBeCloseTo(0.42, 3);
    expect(height(p, firstWall)).toBeCloseTo(0.2, 3);
    const infill = [...p.extrusions.feature].indexOf(p.info.features.indexOf("Sparse infill"));
    expect(width(p, infill)).toBeCloseTo(0.45, 3);
    expect(p.layers.extrusionStart[2]).toBe(p.extrusions.count);
    expect(p.layers.time[0]).toBeGreaterThan(0);
    expect(p.layers.line[1]).toBeGreaterThan(p.layers.line[0]);
  });

  test("from BambuStudio-style comments", () => {
    const p = parseGcode(`; HEADER_BLOCK_START
; model printing time: 1m 0s; total estimated time: 2m 0s
; HEADER_BLOCK_END
M83
; CHANGE_LAYER
; Z_HEIGHT: 0.2
; LAYER_HEIGHT: 0.2
; FEATURE: Inner wall
; LINE_WIDTH: 0.45
G1 X0 Y0 Z0.2 F6000
G1 X10 E0.5 F3000
; CHANGE_LAYER
; Z_HEIGHT: 0.32
; LAYER_HEIGHT: 0.12
G1 Z.32
; FEATURE: Support
G1 X0 E0.3
`);
    expect(p.layers.count).toBe(2);
    expect(p.layers.z[1]).toBeCloseTo(0.32, 5);
    expect(p.layers.height[1]).toBeCloseTo(0.12, 5);
    expect(p.info.features).toContain("Support");
    expect(height(p, p.extrusions.count - 1)).toBeCloseTo(0.12, 3);
    expect(width(p, p.extrusions.count - 1)).toBeCloseTo(0.45, 3);
    // The slicer's estimate wins, spread over the moves.
    expect(p.info.timeSource).toBe("slicer");
    expect(p.info.totalTime).toBe(120);
    const sum = p.layers.time.reduce((a, b) => a + b, 0) + p.info.prepareTime;
    expect(sum).toBeCloseTo(120, 3);
  });

  test("by Z when there are no layer comments; Z hops don't make layers", () => {
    const p = parseGcode(`G90
M83
G1 X0 Y0 Z0.2 F6000
G1 X10 E0.4 F1800
G1 Z0.6
G1 X20
G1 Z0.2
G1 X30 E0.4
G1 Z0.4
G1 X0 E0.4
G1 X0 Y10 E0.4
G1 Z0.6
G1 X10 E0.4
`);
    expect(p.info.layerComments).toBe(false);
    expect(p.layers.count).toBe(3);
    expect([...p.layers.z].map((z) => +z.toFixed(3))).toEqual([0.2, 0.4, 0.6]);
    expect(height(p, p.extrusions.count - 1)).toBeCloseTo(0.2, 3);
    expect(p.info.features).toEqual(["Extrusion"]);
    expect(p.info.timeSource).toBe("estimate");
  });

  test("Cura's per-layer times", () => {
    const p = parseGcode(`;FLAVOR:Marlin
;TIME:100
;Generated with Cura_SteamEngine 5.7.0
M82
G92 E0
;LAYER:0
;TYPE:WALL-OUTER
G0 X0 Y0 Z0.2
G1 X10 E1 F1200
;TIME_ELAPSED:30
;LAYER:1
G0 Z0.4
;TYPE:FILL
G1 X0 E2
;TIME_ELAPSED:100
`);
    expect(p.layers.count).toBe(2);
    expect(p.info.timeSource).toBe("layers");
    expect([...p.layers.time]).toEqual([30, 70]);
    expect(p.info.totalTime).toBe(100);
    expect(p.info.features).toEqual(["Custom", "Outer wall", "Sparse infill"]);
    expect(p.info.generator).toBe("Cura_SteamEngine 5.7.0");
  });
});

describe("extrusion modes", () => {
  const path = (lines: string) => parseGcode(lines);

  test("absolute and relative E give the same extrusions", () => {
    const abs = path(`G90
M82
G92 E0
G1 X0 Y0 Z0.2 F3000
G1 X10 E1
G1 X10 Y10 E2
G1 E1.2
G1 X0 Y10
G1 E2
G1 X0 Y0 E3
G92 E0
G1 X10 Y0 E1
`);
    const rel = path(`G90
M83
G1 X0 Y0 Z0.2 F3000
G1 X10 E1
G1 X10 Y10 E1
G1 E-0.8
G1 X0 Y10
G1 E0.8
G1 X0 Y0 E1
G1 X10 Y0 E1
`);
    expect(segments(abs)).toEqual(segments(rel));
    expect(segments(abs).length).toBe(4);
    expect([...abs.retractions.kind]).toEqual([RETRACT, UNRETRACT]);
    expect([...rel.retractions.kind]).toEqual([RETRACT, UNRETRACT]);
    expect(abs.info.filament[0].mm).toBeCloseTo(4, 5);
    expect(rel.info.filament[0].mm).toBeCloseTo(4, 5);
  });

  test("G91 makes XYZ and E relative; M83 survives G90", () => {
    const p = path(`G90
M83
G1 X5 Y5 Z0.2 F3000
G91
G1 X10 E1
G1 Y10 E1
G90
G1 X5 Y5 E1
`);
    expect(segments(p)).toEqual([
      [5, 5, 0.2, 15, 5, 0.2],
      [15, 5, 0.2, 15, 15, 0.2],
      [15, 15, 0.2, 5, 5, 0.2],
    ]);
  });

  test("G92 shifts the coordinates", () => {
    const p = path(`G90
M83
G1 X10 Y10 Z0.2
G92 X0 Y0
G1 X5 E1
`);
    expect(segments(p)).toEqual([[10, 10, 0.2, 15, 10, 0.2]]);
  });

  test("a move that retracts as it goes is a wipe; travels leave gaps in the chain", () => {
    const p = path(`M83
G1 X0 Y0 Z0.2
G1 X10 E1
G1 X15 E-0.5
G1 X30 Y30
G1 X40 E1
`);
    expect([...p.travels.kind]).toEqual([0, WIPE, 0]);
    expect(p.extrusions.count).toBe(3);
    expect(p.extrusions.feature[1]).toBe(GAP);
    expect([...p.extrusions.points.subarray(6, 9)]).toEqual([30, 30, 0.2 as number].map(Math.fround));
    expect(p.travels.at[2]).toBe(1);
  });

  test("firmware retraction", () => {
    const p = path(`M83
G1 X0 Y0 Z0.2
G1 X10 E1
G10
G1 X20
G11
G10 P0 L1 X1
`);
    expect([...p.retractions.kind]).toEqual([RETRACT, UNRETRACT]);
    expect([...p.retractions.pos.subarray(3, 6)]).toEqual([20, 0, Math.fround(0.2)]);
  });

  test("width from E when no comment says", () => {
    // 0.4 x 0.2 mm bead: area (w - h) h + pi (h/2)^2 per mm of path.
    const area = (0.4 - 0.2) * 0.2 + Math.PI * 0.01;
    const e = (area / (Math.PI * 0.875 * 0.875)) * 20;
    const p = path(`M83
G1 X0 Y0 Z0.2
G1 X20 E${e.toFixed(6)}
`);
    expect(width(p, 0)).toBeCloseTo(0.4, 2);
    // ... and from the file's filament diameter when it isn't 1.75 mm.
    const thick = path(`M83
G1 X0 Y0 Z0.2
G1 X20 E${((area / (Math.PI * 1.425 * 1.425)) * 20).toFixed(6)}
; filament_diameter = 2.85
`);
    expect(width(thick, 0)).toBeCloseTo(0.4, 2);
  });

  test("line numbers and checksums, lower case, inches", () => {
    const p = path(`N10 G90*45
N11 M83*12
n12 g1 x0 y0 z0.2*3
G20
G1 X1 E0.1 ; one inch
`);
    expect(segments(p)).toEqual([[0, 0, 0.2, 25.4, 0, 0.2]]);
  });
});

describe("arcs", () => {
  test("G2/G3 with I/J follow the circle and end where they say", () => {
    const p = parseGcode(`G90
M83
G1 X10 Y0 Z0.2
G3 X0 Y10 I-10 J0 E1
`);
    const segs = segments(p);
    expect(segs.length).toBeGreaterThan(4);
    for (const s of segs) expect(Math.hypot(s[3], s[4])).toBeCloseTo(10, 3);
    expect(segs.at(-1)!.slice(3)).toEqual([0, 10, 0.2]);
    // Counter-clockwise: through (7.07, 7.07), not round the long way.
    expect(segs.every((s) => s[3] >= -1e-3 && s[4] >= -1e-3)).toBe(true);
    const total = p.info.filament[0].mm;
    expect(total).toBeCloseTo(1, 5);
  });

  test("clockwise, R form, full circle and helical Z", () => {
    const cw = segments(parseGcode(`M83
G1 X0 Y0 Z0.2
G2 X10 Y0 R5 E1
`));
    expect(cw.every((s) => s[4] >= -1e-3)).toBe(true); // over the top
    expect(Math.max(...cw.map((s) => s[4]))).toBeCloseTo(5, 1);

    const full = segments(parseGcode(`M83
G1 X10 Y0 Z1
G2 I-10 J0 Z2 E1
`));
    expect(full.at(-1)!.slice(3)).toEqual([10, 0, 2]);
    expect(Math.min(...full.map((s) => s[3]))).toBeCloseTo(-10, 1);
    // Z climbs steadily.
    for (let i = 1; i < full.length; i++) expect(full[i][5]).toBeGreaterThan(full[i - 1][5]);
  });
});

