describe("header and streaming", () => {
  const FILE = `; generated by PrusaSlicer 2.8.0+win64 on 2026-01-01 at 10:00:00 UTC
; thumbnail begin 16x16 120
; iVBORw0KGgoAAAANSUhEUgAAABAAAAAQCAYAAAAf8/9hAAAAGklEQVR4AWMYBaNgFIyCUTAKRsEoGAWjYBQAAAZmAAH
; G1 X999 Y999 E99
; thumbnail end
M83
;LAYER_CHANGE
;Z:0.2
;HEIGHT:0.2
G1 X0 Y0 Z0.2 F6000
;TYPE:External perimeter
;WIDTH:0.45
G2 X10 Y0 I5 J0 E0.5 F2400
G1 X10 Y10 E0.5
G1 E-0.8 F2100
G1 X50 Y50 F9000
G1 E0.8
G1 X60 Y50 E0.5
; estimated printing time (normal mode) = 1m 30s
; bed_shape = 0x0,250x0,250x210,0x210
; max_print_height = 220
`;

  test("settings at the end of the file still count; thumbnails are skipped", () => {
    const p = parseGcode(FILE);
    expect(p.info.generator).toBe("PrusaSlicer 2.8.0+win64");
    expect(p.info.bed).toEqual({ area: [[0, 0], [250, 0], [250, 210], [0, 210]], height: 220 });
    expect(p.info.totalTime).toBe(90);
    expect(p.info.bounds!.max[0]).toBeLessThan(100);
  });

  test("any chunking gives the same result", () => {
    const whole = parseGcode(FILE);
    const bytes = new TextEncoder().encode(FILE);
    for (const size of [1, 7, 64]) {
      const parser = new GcodeParser();
      for (let i = 0; i < bytes.length; i += size) parser.push(bytes.subarray(i, i + size));
      const p = parser.done();
      expect(p.extrusions.count).toBe(whole.extrusions.count);
      expect([...p.extrusions.points]).toEqual([...whole.extrusions.points]);
      expect([...p.layers.time]).toEqual([...whole.layers.time]);
      expect(p.info.meta).toEqual(whole.info.meta);
      expect(p.info.lines).toBe(whole.info.lines);
    }
  });

  test("durations", () => {
    expect(parseDuration("1d 2h 3m 4s")).toBe(93784);
    expect(parseDuration("46m 15s")).toBe(2775);
    expect(Number.isNaN(parseDuration("soon"))).toBe(true);
  });
});
