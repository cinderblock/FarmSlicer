// Unit tests of where a running print is in its G-code
// (src/components/preview/live.ts): `bun test` in web/.
import { describe, expect, test } from "bun:test";
import { GcodeParser, parseGcode } from "../src/components/preview/parser";
import { layerOfSegment, livePosition, segmentAtFraction, segmentAtOffset } from "../src/components/preview/live";

/** Three layers of two equal 20 mm lines each, at the same speed. */
const file = `; generated by OrcaSlicer 2.4.2
G90
M83
G1 X0 Y0 Z0.2 F6000
;LAYER_CHANGE
;Z:0.2
;HEIGHT:0.2
;TYPE:Outer wall
;WIDTH:0.42
G1 X20 Y0 E1 F1200
G1 X20 Y20 E1
;LAYER_CHANGE
;Z:0.4
;HEIGHT:0.2
G1 Z0.4
G1 X0 Y20 E1
G1 X0 Y0 E1
;LAYER_CHANGE
;Z:0.6
;HEIGHT:0.2
G1 Z0.6
G1 X20 Y0 E1
G1 X20 Y20 E1
`;
const parsed = parseGcode(file);
const { layers } = parsed;
const start = (l: number) => layers.extrusionStart[l];
const end = (l: number) => layers.extrusionStart[l + 1];

describe("livePosition", () => {
  test("the file has three layers", () => {
    expect(layers.count).toBe(3);
  });

  test("the printer's layer, at its start without a clock", () => {
    const pos = livePosition(parsed, { layer: 2, totalLayers: 3 }, null)!;
    expect(pos.layer).toBe(1);
    expect(pos.upTo).toBe(start(1));
    expect(pos.source).toBe("layer");
    expect(pos.layerMismatch).toBe(false);
  });

  test("layer 0 (start sequence) is the file's first layer", () => {
    expect(livePosition(parsed, { layer: 0 }, null)!.layer).toBe(0);
  });

  test("layers past the end clamp, and a different count is flagged", () => {
    const pos = livePosition(parsed, { layer: 9, totalLayers: 9 }, null)!;
    expect(pos.layer).toBe(2);
    expect(pos.layerMismatch).toBe(true);
  });

  test("time in the layer moves the position, never to its end", () => {
    const half = livePosition(parsed, { layer: 3 }, layers.time[2] * 0.6)!;
    expect(half.upTo).toBeGreaterThan(start(2));
    expect(half.upTo).toBeLessThan(end(2) + 1);
    const late = livePosition(parsed, { layer: 3 }, layers.time[2] * 10)!;
    expect(late.upTo).toBeLessThanOrEqual(end(2));
  });

  test("a percentage maps onto the file's time", () => {
    expect(livePosition(parsed, { percent: 0 }, null)!.layer).toBe(0);
    expect(livePosition(parsed, { percent: 100 }, null)!.layer).toBe(2);
    expect(livePosition(parsed, { percent: 100 }, null)!.upTo).toBe(end(2));
    expect(livePosition(parsed, { percent: 50 }, null)!.source).toBe("percent");
  });

  test("done shows everything", () => {
    const pos = livePosition(parsed, { done: true, layer: 1 }, null)!;
    expect(pos).toEqual({ layer: 2, upTo: end(2), source: "done", layerMismatch: false });
  });
});

describe("segmentAtFraction", () => {
  test("bounds", () => {
    expect(segmentAtFraction(parsed, 1, 0)).toBe(start(1));
    expect(segmentAtFraction(parsed, 1, 1)).toBe(end(1));
  });
  test("monotonic", () => {
    let prev = start(2);
    for (let f = 0; f <= 1; f += 0.1) {
      const s = segmentAtFraction(parsed, 2, f);
      expect(s).toBeGreaterThanOrEqual(prev);
      prev = s;
    }
  });
});

describe("file positions", () => {
  const bytes = new TextEncoder().encode(file);
  /** Byte offset of the first line containing `text`. */
  const at = (text: string) => file.indexOf(text);

  test("each segment knows the byte offset of its line", () => {
    const { offset, count } = parsed.extrusions;
    expect(count).toBeGreaterThan(0);
    for (let i = 1; i < count; i++) expect(offset[i]).toBeGreaterThanOrEqual(offset[i - 1]);
    // The first extrusion is the line "G1 X20 Y0 E1 F1200".
    const first = at("G1 X20 Y0 E1 F1200");
    const i = [...offset].indexOf(first);
    expect(i).toBeGreaterThanOrEqual(0);
    expect(offset[count - 1]).toBe(file.lastIndexOf("G1 X20 Y20 E1"));
  });

  test("offsets survive any chunking", () => {
    const parser = new GcodeParser();
    for (let i = 0; i < bytes.length; i += 7) parser.push(bytes.subarray(i, i + 7));
    expect([...parser.done().extrusions.offset]).toEqual([...parsed.extrusions.offset]);
  });

  test("a printer's place in the file is the move it read last", () => {
    // Just past the second layer's first extrusion line.
    const line = at("G1 X0 Y20 E1");
    const pos = livePosition(parsed, { filePosition: line + 5, layer: 1 }, null)!;
    expect(pos.source).toBe("file");
    expect(pos.layer).toBe(1);
    expect(parsed.extrusions.offset[pos.upTo - 1]).toBe(line);
    expect(segmentAtOffset(parsed, 0)).toBe(0);
    expect(segmentAtOffset(parsed, bytes.length)).toBe(parsed.extrusions.count);
    expect(layerOfSegment(parsed, parsed.extrusions.count - 1)).toBe(2);
  });
});
